/**
 * Tarjeta compacta de una asignación para el carrusel del panel del docente.
 *
 * Muestra el curso, la unidad y el resumen de la prueba final. La asignación
 * solo trae los identificadores, así que los nombres los resuelve la pantalla
 * que lista. Tocar la tarjeta abre el detalle de la asignación.
 */
@Composable
fun AssignmentCarouselCard(
    assignment: Assignment,
    courseName: String,
    unitTitle: String,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    Card(
        onClick = onClick,
        modifier = modifier
            .fillMaxWidth()
            .height(160.dp),
        shape = RoundedCornerShape(16.dp)
    ) {
        Row(
            modifier = Modifier
                .fillMaxSize()
                .padding(16.dp),
            horizontalArrangement = Arrangement.spacedBy(12.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Box(
                modifier = Modifier
                    .size(40.dp)
                    .clip(CircleShape)
                    .background(MaterialTheme.colorScheme.primaryContainer),
                contentAlignment = Alignment.Center
            ) {
                Icon(
                    imageVector = Icons.AutoMirrored.Filled.Assignment,
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.onPrimaryContainer,
                    modifier = Modifier.size(22.dp)
                )
            }

            Column(
                modifier = Modifier.weight(1f),
                verticalArrangement = Arrangement.spacedBy(4.dp)
            ) {
                Text(
                    text = courseName,
                    style = MaterialTheme.typography.labelLarge,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )

                Text(
                    text = unitTitle,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.SemiBold,
                    maxLines = 2,
                    overflow = TextOverflow.Ellipsis
                )

                Text(
                    text = finalTestSummary(assignment),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
            }

            Icon(
                imageVector = Icons.AutoMirrored.Filled.KeyboardArrowRight,
                contentDescription = null,
                tint = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.size(20.dp)
            )
        }
    }
}

/** Resumen de la prueba final de la asignación. */
private fun finalTestSummary(assignment: Assignment): String {
    if (!assignment.pruebaFinalHabilitada) {
        return "Sin prueba final"
    }

    val maxAttempts = assignment.maxIntentos ?: return "Prueba final · Sin límite"

    return "Prueba final · ${attemptsLabel(maxAttempts)}"
}

/** Texto de la cantidad de intentos, con singular y plural. */
private fun attemptsLabel(count: Int): String =
    if (count == 1) "1 intento" else "$count intentos"
